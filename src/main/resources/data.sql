-- Backfill de cuenta_padre_id: el padre de una cuenta es la cuenta cuyo codigo
-- es el prefijo correspondiente (1 digito para nivel 2, 2 digitos para nivel 3, 4 digitos para nivel 4).
UPDATE cuenta AS hijo
    JOIN cuenta AS padre
ON padre.codigo = CASE
    WHEN CHAR_LENGTH (hijo.codigo) = 2 THEN LEFT (hijo.codigo, 1)
    WHEN CHAR_LENGTH (hijo.codigo) = 4 THEN LEFT (hijo.codigo, 2)
    WHEN CHAR_LENGTH (hijo.codigo) = 6 THEN LEFT (hijo.codigo, 4)
END
SET
hijo.cuenta_padre_id = padre.id
WHERE CHAR_LENGTH(hijo.codigo) > 1;